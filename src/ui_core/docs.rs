//! The documentation pages Seeker can send you to.
//!
//! A typed query that is not a command, not a conversation and not a screen is
//! usually a question the documentation answers, so the same field that finds
//! your sessions also finds the page for what you are asking about (#2461).
//!
//! The index is the site's own table of contents, not a hand-picked sample:
//! every path below was read from https://docs.opencrabs.com/sitemap.xml, and
//! every title is the one that page publishes, so a row opens the real page and
//! the user lands on the answer rather than on a docs home page (#2462). The
//! 23 case studies under `/stories/` are deliberately out of the index: they
//! are long posts about one deployment, and indexed they outrank the reference
//! page that answers the same word (the Telegram story beating
//! `/channels/telegram.html`). Their hub page stays in.
//!
//! There is no query parameter to link: the site's search runs client-side on a
//! hashed bundle and never reads `location.search`, so a `?search=` URL would
//! drop what the user typed. Pointing at the page is the honest option.
//!
//! [`PAGES`] is generated by `scripts/gen-docs-index.py`; the pinned
//! [`SITEMAP`] is the coverage contract, so a page that ships later fails the
//! suite instead of quietly missing from the card.
//!
//! This module stays pure: it builds rows and URLs, the frontends open them.

use super::palette::{PaletteAction, PaletteItem, PaletteKind};

/// Where the pages live. The URL is composed here, so both frontends send the
/// user to the same host.
