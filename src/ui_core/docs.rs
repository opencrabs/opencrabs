/// The curated pages. A function rather than a bare const so the call sites
/// read the same as `channel_items()` and the tests can iterate it.
pub fn pages() -> &'static [DocPage] {
    PAGES
}

/// The URL a row opens. Composed here so the host is written once.
pub fn url(path: &str) -> String {
    format!("{DOCS_BASE}{path}")
}

/// The muted line under a row: the section the page lives in, read off its own
/// path so it cannot drift from the link printed beside it.
pub fn breadcrumb(path: &str) -> &'static str {
    let rest = path.trim_start_matches('/');
    match rest.split('/').next() {
        Some("getting-started") if rest.contains('/') => "getting started",
        Some("features") if rest.contains('/') => "features",
        Some("channels") if rest.contains('/') => "channels",
        Some("brain") if rest.contains('/') => "brain",
        Some("development") if rest.contains('/') => "development",
        _ => "docs.opencrabs.com",
    }
}

/// One row per page, each carrying the path it opens and the words that should
/// find it. The card paints these; the frontends only apply the action.
pub fn items() -> Vec<PaletteItem> {
    PAGES
        .iter()
        .map(|page| {
            let mut row = PaletteItem::new(
                page.title,
                breadcrumb(page.path),
                PaletteKind::Docs,
                PaletteAction::OpenDocs(page.path),
            );
            row.keywords = page.keywords.to_string();
            row
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ui_core::palette::PaletteState;

    /// Keep the deterministic coverage check on the generator's exclusion
    /// contract. Live URL discovery belongs to the Python checker, not here.
    fn is_reference_path(path: &str) -> bool {
        !matches!(path, "/" | "/toc.html" | "/getting-started/videos.html")
            && !path.starts_with("/stories/")
    }

    /// Every path must be the shape the sitemap publishes, or the row ships a
    /// 404 the user cannot tell from a docs outage.
    #[test]
    fn every_doc_path_is_a_published_shape() {
        for page in pages() {
            assert!(
                page.path.starts_with('/'),
                "{} must start with a slash",
                page.path
            );
            assert!(
                page.path.ends_with(".html"),
                "{} must be a page, not a directory",
                page.path
            );
            assert!(
                !page.path.contains(' ') && !page.path.contains("//"),
                "{} is not a clean path",
                page.path
            );
            assert!(
                !page.title.trim().is_empty() && !page.keywords.trim().is_empty(),
                "{} needs a title and keywords",
                page.path
            );
        }
    }

    /// Two rows with the same title are indistinguishable in the card, and the
    /// user cannot tell which one they are about to open.
    #[test]
    fn doc_titles_are_unique() {
        let mut seen: Vec<&str> = Vec::new();
        for page in pages() {
            assert!(
                !seen.contains(&page.title),
                "duplicate title {}",
                page.title
            );
            seen.push(page.title);
        }
    }

    /// The index is the site's table of contents, not a sample: every reference
    /// page the sitemap publishes has a row, and every row points at a page the
    /// sitemap publishes. A page that ships later fails here instead of
    /// silently missing from the card (#2462).
    #[test]
    fn the_index_covers_every_published_page() {
        for path in SITEMAP {
            if !is_reference_path(path) {
                continue;
            }
            assert!(
                pages().iter().any(|page| page.path == *path),
                "{path} is published but has no row"
            );
        }
        for page in pages() {
            assert!(
                SITEMAP.contains(&page.path),
                "{} is not a published page",
                page.path
            );
        }
    }

    /// The case studies stay out, and the reason is a ranking one: with them in
    /// the index the word `telegram` would arm a story above the setup page.
    #[test]
    fn the_case_studies_stay_out_of_the_index() {
        assert!(
            pages()
                .iter()
                .all(|page| !page.path.starts_with("/stories/"))
        );
        assert!(pages().iter().any(|page| page.path == "/user-stories.html"));
    }

    /// Non-reference pages stay pinned in the sitemap but never become rows.
    #[test]
    fn non_reference_pages_are_explicitly_excluded() {
        for path in ["/", "/toc.html", "/getting-started/videos.html"] {
            assert!(SITEMAP.contains(&path), "{path} left the pinned sitemap");
            assert!(!is_reference_path(path));
            assert!(pages().iter().all(|page| page.path != path));
        }
        assert!(SITEMAP.iter().any(|path| path.starts_with("/stories/")));
        assert!(SITEMAP.iter().all(|path| {
            is_reference_path(path) == pages().iter().any(|page| page.path == *path)
        }));
    }

    /// A page whose title is the bare section name is unreadable in the card,
    /// so the index carries a row title a person can scan.
    #[test]
    fn row_titles_read_as_pages_not_as_sections() {
        for page in pages() {
            assert!(
                page.title.len() > 3,
                "{} has a title too short to read",
                page.path
            );
            assert!(
                !page.title.eq_ignore_ascii_case("overview"),
                "{} is titled Overview",
                page.path
            );
        }
    }

    /// The composed URL is the one the browser must open, exactly.
    #[test]
    fn urls_are_composed_from_the_documented_host() {
        assert_eq!(
            url("/features/voice.html"),
            "https://docs.opencrabs.com/features/voice.html"
        );
        assert_eq!(DOCS_BASE, "https://docs.opencrabs.com");
    }

    /// The muted line is derived, not typed twice, so it cannot drift from the
    /// path printed next to it.
    #[test]
    fn breadcrumbs_read_the_section_off_the_path() {
        assert_eq!(
            breadcrumb("/getting-started/installation.html"),
            "getting started"
        );
        assert_eq!(breadcrumb("/channels/discord.html"), "channels");
        assert_eq!(breadcrumb("/changelog.html"), "docs.opencrabs.com");
    }

    /// One row per page, each carrying the path it opens and no other action.
    #[test]
    fn every_page_becomes_exactly_one_docs_row() {
        let rows = items();
        assert_eq!(rows.len(), pages().len());
        for (row, page) in rows.iter().zip(pages()) {
            assert_eq!(row.kind, PaletteKind::Docs);
            assert_eq!(row.title, page.title);
            assert_eq!(row.action, PaletteAction::OpenDocs(page.path));
        }
    }

    /// The point of the feature: a typed question lands on the page that
    /// answers it. If this breaks, the rows exist and nobody can reach them.
    #[test]
    fn typing_a_topic_arms_its_page() {
        let mut state = PaletteState::new(items());
        for c in "telegram".chars() {
            state.type_char(c);
        }
        let top = state.visible().into_iter().next().expect("a match");
        assert_eq!(
            top.item.action,
            PaletteAction::OpenDocs("/channels/telegram.html")
        );

        let mut state = PaletteState::new(items());
        for c in "voice".chars() {
            state.type_char(c);
        }
        let top = state.visible().into_iter().next().expect("a match");
        assert_eq!(
            top.item.action,
            PaletteAction::OpenDocs("/features/voice.html")
        );
    }
}
